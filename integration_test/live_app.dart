// Local acceptance entry point only. It restores server-issued test sessions;
// every business read and write goes to the actual backend/SQL Server.
import 'dart:convert';
import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:hrm_coffee_shop_flutter/app/app.dart';
import 'package:hrm_coffee_shop_flutter/app/router/app_router.dart';
import 'package:hrm_coffee_shop_flutter/core/network/api_providers.dart';
import 'package:hrm_coffee_shop_flutter/core/storage/session_store.dart';
import 'package:hrm_coffee_shop_flutter/features/auth/data/session_controller.dart';
import 'package:hrm_coffee_shop_flutter/shared/resources/data/resource_repository.dart';

class AcceptanceSessionStore implements SessionStore {
  AcceptanceSessionStore(this.sessions) {
    select('employee');
  }
  final Map<String, dynamic> sessions;
  final Map<String, String> values = {};
  String? activeActor;
  void select(String actor) {
    final previousActor = activeActor;
    if (previousActor != null) {
      sessions[previousActor] = {
        ...Map<String, dynamic>.from(sessions[activeActor] as Map),
        'accessToken': values['access'],
        'refreshToken': values['refresh'],
      };
    }
    final session = Map<String, dynamic>.from(sessions[actor] as Map);
    values['access'] = session['accessToken'] as String;
    values['refresh'] = session['refreshToken'] as String;
    activeActor = actor;
  }

  @override
  Future<String?> read(String key) async {
    if (key == 'device-credential') {
      final credential = values[key] ??
          await const SecureSessionStore().read('acceptance-device-credential');
      if (credential != null) {
        values[key] = credential;
        await const SecureSessionStore().write(
          'acceptance-device-credential',
          credential,
        );
      }
      return credential;
    }
    return values[key];
  }

  @override
  Future<void> write(String key, String value) async {
    values[key] = value;
    if (key == 'device-credential') {
      await const SecureSessionStore().write(
        'acceptance-device-credential',
        value,
      );
    }
  }

  @override
  Future<void> delete(String key) async {
    values.remove(key);
  }
}

void main() {
  WidgetsFlutterBinding.ensureInitialized();
  if (!kDebugMode) {
    throw StateError('The local acceptance entry point is debug-only.');
  }
  const encoded = String.fromEnvironment('ACCEPTANCE_SESSIONS');
  if (encoded.isEmpty) {
    throw StateError('Test sessions must be generated by V3WorkflowIT first.');
  }
  final store = AcceptanceSessionStore(
    Map<String, dynamic>.from(jsonDecode(encoded) as Map),
  );
  runApp(
    ProviderScope(
      overrides: [sessionStoreProvider.overrideWithValue(store)],
      child: AcceptanceShell(store),
    ),
  );
}

class AcceptanceShell extends ConsumerWidget {
  const AcceptanceShell(this.store, {super.key});
  final AcceptanceSessionStore store;
  @override
  Widget build(BuildContext context, WidgetRef ref) => Directionality(
        textDirection: TextDirection.ltr,
        child: Column(
          children: [
            Material(
              color: const Color(0xff25211e),
              child: SafeArea(
                bottom: false,
                child: SizedBox(
                  height: 44,
                  child: Row(
                    children: [
                      const Padding(
                        padding: EdgeInsets.symmetric(horizontal: 8),
                        child: Text(
                          'TEST',
                          style: TextStyle(color: Colors.white70, fontSize: 11),
                        ),
                      ),
                      for (final actor in ['employee', 'manager', 'admin'])
                        Expanded(
                          child: TextButton(
                            onPressed: () async {
                              store.select(actor);
                              await ref
                                  .read(sessionProvider.notifier)
                                  .restore();
                              ref.read(dataRevisionProvider.notifier).changed();
                              ref.read(routerProvider).go('/');
                            },
                            child: Text(
                              actor,
                              style: const TextStyle(
                                color: Colors.white,
                                fontSize: 12,
                              ),
                            ),
                          ),
                        ),
                    ],
                  ),
                ),
              ),
            ),
            const Expanded(child: BeanHubApp()),
          ],
        ),
      );
}
