package com.hrm.coffeeshop.shared.service;

import com.hrm.coffeeshop.shared.dto.ViolationDto.ViolationView;

import com.hrm.coffeeshop.common.*;
import com.hrm.coffeeshop.domain.*;
import com.hrm.coffeeshop.repository.*;
import org.springframework.data.domain.Pageable;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Clock;
import java.util.Map;

/**
 * Sự kiện vi phạm (SRS 7.4 ViolationEvent). Sự kiện tự động chỉ được GHI NHẬN (PENDING) và không khấu trừ tiền;
 * người có thẩm quyền xác nhận hoặc bác bỏ. Tiền phạt là quyết định riêng (EmployeeRewardPenalty, DecisionType = PENALTY).
 * Ánh xạ trạng thái: PENDING→OPEN, APPROVED→CONFIRMED, REJECTED→DISMISSED, APPLIED→RESOLVED.
 */
@Service
public class ViolationService {
    private final ViolationEventRepository records;
    private final RuleCatalogRepository rules;
    private final PersonLookup people;
    private final NotificationService notifications;
    private final AuditService audit;
    private final Clock clock;

    public ViolationService(ViolationEventRepository records, RuleCatalogRepository rules, PersonLookup people,
                            NotificationService notifications, AuditService audit, Clock clock) {
        this.records = records;
        this.rules = rules;
        this.people = people;
        this.notifications = notifications;
        this.audit = audit;
        this.clock = clock;
    }

    static String apiStatus(String db) {
        return switch (db) {
            case "PENDING" -> "OPEN";
            case "APPROVED" -> "CONFIRMED";
            case "REJECTED" -> "DISMISSED";
            case "APPLIED" -> "RESOLVED";
            default -> db;
        };
    }

    static String dbStatus(String api) {
        return switch (api) {
            case "OPEN", "UNDER_REVIEW" -> "PENDING";
            case "CONFIRMED" -> "APPROVED";
            case "DISMISSED" -> "REJECTED";
            case "RESOLVED" -> "APPLIED";
            default -> api;
        };
    }

    @Transactional
    public void recordLate(Employee emp, Long attendanceId, int lateMinutes) {
        rules.findByRuleCode("LATE_MINOR").filter(r -> Boolean.TRUE.equals(r.getIsActive())).ifPresent(rule -> {
            if (records.existsByEmployeeIdAndRuleIdAndAttendanceId(emp.getEmployeeId(), rule.getRuleId(), attendanceId)) return;
            create(emp.getEmployeeId(), rule, attendanceId, null, "Đi muộn " + lateMinutes + " phút sau ân hạn");
        });
    }

    @Transactional
    public void recordChecklistMissed(Long employeeId, Long checklistTaskId) {
        rules.findByRuleCode("CHECKLIST_MISSED").filter(r -> Boolean.TRUE.equals(r.getIsActive())).ifPresent(rule -> {
            if (records.existsByEmployeeIdAndRuleIdAndChecklistTaskId(employeeId, rule.getRuleId(), checklistTaskId)) return;
            create(employeeId, rule, null, checklistTaskId, "Bỏ sót checklist sau khi hết số lần nhắc");
        });
    }

    @Transactional
    public void recordAttendanceSpotCheckMissed(Long employeeId, Long attendanceId) {
        rules.findByRuleCode("ATTENDANCE_SPOT_CHECK_MISSED")
                .filter(r -> Boolean.TRUE.equals(r.getIsActive())).ifPresent(rule -> {
                    if (records.existsByEmployeeIdAndRuleIdAndAttendanceId(employeeId, rule.getRuleId(), attendanceId)) return;
                    create(employeeId, rule, attendanceId, null,
                            "Không phản hồi yêu cầu kiểm tra hiện diện giữa ca trong 5 phút");
                });
    }

    private void create(Long employeeId, RuleCatalog rule, Long attId, Long taskId, String details) {
        ViolationEvent d = new ViolationEvent();
        d.setEmployeeId(employeeId);
        d.setRuleId(rule.getRuleId());
        d.setAttendanceId(attId);
        d.setChecklistTaskId(taskId);
        d.setSourceType(attId != null ? "ATTENDANCE" : "CHECKLIST");
        d.setSourceId(attId != null ? attId : taskId);
        d.setDetails(details);
        d.setIsAutoGenerated(true);
        d.setRecordStatus("PENDING");
        records.save(d);
        audit.log("VIOLATION_AUTO_RECORDED", "ViolationEvent", d.getViolationEventId(), null,
                Map.of("rule", rule.getRuleCode(), "employeeId", employeeId));
        notifications.notifyRole(Roles.STORE_MANAGER, "VIOLATION_PENDING", "Có vi phạm cần xem xét",
                rule.getRuleName() + ": " + people.nameOf(employeeId), "ViolationEvent", d.getViolationEventId());
    }

    ViolationView view(ViolationEvent d) {
        RuleCatalog r = rules.findById(d.getRuleId()).orElse(null);
        return new ViolationView(d.getViolationEventId(), d.getEmployeeId(), people.nameOf(d.getEmployeeId()),
                r == null ? null : r.getRuleCode(), r == null ? null : r.getRuleName(), r == null ? null : r.getSeverity(),
                d.getAttendanceId(), d.getChecklistTaskId(), TimeUtils.vn(d.getOccurredAt()), d.getDetails(),
                apiStatus(d.getRecordStatus()), Boolean.TRUE.equals(d.getIsAutoGenerated()), d.getReviewNote(),
                TimeUtils.vn(d.getReviewedAt()));
    }

    @Transactional(readOnly = true)
    public PageResponse<ViolationView> list(String status, Long employeeId, Pageable p) {
        return PageResponse.of(records.search(status == null || status.isBlank() ? "" : dbStatus(status),
                employeeId == null ? 0L : employeeId, p), this::view);
    }

    @Transactional(readOnly = true)
    public ViolationView get(Long id) {
        ViolationEvent d = records.findById(id).orElseThrow(() -> BusinessException.notFound("vi phạm"));
        AuthUser u = SecurityUtils.current();
        if (!d.getEmployeeId().equals(u.employeeId()) && !u.isStaffReviewer() && !u.hasPermission(Permissions.VIOLATION_REVIEW))
            throw BusinessException.forbidden("Bạn không có quyền xem vi phạm này");
        return view(d);
    }

    @Transactional
    public ViolationView confirm(Long id, String note) { return decide(id, "APPROVED", note); }

    @Transactional
    public ViolationView dismiss(Long id, String reason) {
        if (reason == null || reason.isBlank()) throw new BusinessException(ErrorCode.VALIDATION_ERROR, "Phải nhập lý do bác bỏ");
        return decide(id, "REJECTED", reason.trim());
    }

    private ViolationView decide(Long id, String status, String note) {
        ViolationEvent d = records.findById(id).orElseThrow(() -> BusinessException.notFound("vi phạm"));
        RuleCatalog rule = rules.findById(d.getRuleId()).orElseThrow();
        AuthUser u = SecurityUtils.current();
        SecurityUtils.requirePermission(Permissions.VIOLATION_REVIEW);
        if ("CRITICAL".equals(rule.getSeverity())) RewardPenaltyService.requireAuthority(u, rule.getSeverity(), null, 0);
        if (!"PENDING".equals(d.getRecordStatus())) throw BusinessException.invalidState("Vi phạm không ở trạng thái chờ xem xét");
        if (people.userIdOf(d.getEmployeeId()).equals(u.userId()))
            throw BusinessException.forbidden("Không thể tự xem xét vi phạm của chính mình");
        d.setRecordStatus(status);
        d.setReviewedBy(u.userId());
        d.setReviewedAt(clock.instant());
        d.setReviewNote(note);
        audit.log("VIOLATION_" + status, "ViolationEvent", id, Map.of("status", "PENDING"),
                Map.of("status", status, "note", String.valueOf(note)));
        notifications.notify(people.userIdOf(d.getEmployeeId()), "VIOLATION_REVIEWED", "Kết quả xem xét vi phạm",
                "APPROVED".equals(status) ? "Vi phạm đã được xác nhận." : "Vi phạm đã được bác bỏ.",
                "ViolationEvent", id, null);
        return view(d);
    }
}
