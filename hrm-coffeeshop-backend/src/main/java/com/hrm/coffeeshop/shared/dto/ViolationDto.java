package com.hrm.coffeeshop.shared.dto;

import jakarta.validation.constraints.*;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.OffsetDateTime;

public final class ViolationDto {
    private ViolationDto() {}

    public record ViolationView(Long violationId, Long employeeId, String employeeName, String ruleCode, String ruleName,
                                String severity, Long attendanceId, Long checklistRunId, OffsetDateTime incidentAt,
                                String details, String status, boolean autoGenerated,
                                String reviewNote, OffsetDateTime reviewedAt) {}

    public record DecisionRequest(@NotBlank @Pattern(regexp = "REWARD|PENALTY") String decisionType,
                                  @NotNull Long employeeId, @NotBlank @Size(max = 40) String reasonCode,
                                  @NotBlank @Size(max = 1000) String description,
                                  @DecimalMin("0") @DecimalMax("1000000000") BigDecimal amount, LocalDate effectiveDate) {}

    public record DecisionView(String decisionId, String decisionType, Long employeeId, String employeeName,
                               String reasonCode, String reasonName, String severity, String description,
                               BigDecimal amount, String status, Long createdBy, Long reviewedBy, String reviewNote,
                               OffsetDateTime effectiveAt) {}
}
