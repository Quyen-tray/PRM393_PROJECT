package com.hrm.coffeeshop.domain;

import jakarta.persistence.*;
import java.io.Serializable;
import java.math.BigDecimal;
import java.time.*;
import java.util.Objects;

/** Sinh tự động từ DDL bởi tools/gen_entities.py - đừng sửa tay. */
@Entity
@Table(name = "ViolationEvent")
public class ViolationEvent {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "ViolationEventId")
    private Long violationEventId;
    @Column(name = "EmployeeId")
    private Long employeeId;
    @Column(name = "RuleId")
    private Integer ruleId;
    @Column(name = "AttendanceId")
    private Long attendanceId;
    @Column(name = "ChecklistTaskId")
    private Long checklistTaskId;
    @Column(name = "OccurredAt")
    private Instant occurredAt = Instant.now();
    @Column(name = "SourceType")
    private String sourceType = "MANUAL";
    @Column(name = "SourceId")
    private Long sourceId;
    @Column(name = "EvidenceReference")
    private String evidenceReference;
    @Column(name = "Details")
    private String details;
    @Column(name = "RecordStatus")
    private String recordStatus = "PENDING";
    @Column(name = "IsAutoGenerated")
    private Boolean isAutoGenerated = Boolean.FALSE;
    @Column(name = "CreatedBy")
    private Long createdBy;
    @Column(name = "ReviewedBy")
    private Long reviewedBy;
    @Column(name = "ReviewedAt")
    private Instant reviewedAt;
    @Column(name = "ReviewNote")
    private String reviewNote;

    public ViolationEvent() {}

    public Long getViolationEventId() { return violationEventId; }
    public void setViolationEventId(Long violationEventId) { this.violationEventId = violationEventId; }
    public Long getEmployeeId() { return employeeId; }
    public void setEmployeeId(Long employeeId) { this.employeeId = employeeId; }
    public Integer getRuleId() { return ruleId; }
    public void setRuleId(Integer ruleId) { this.ruleId = ruleId; }
    public Long getAttendanceId() { return attendanceId; }
    public void setAttendanceId(Long attendanceId) { this.attendanceId = attendanceId; }
    public Long getChecklistTaskId() { return checklistTaskId; }
    public void setChecklistTaskId(Long checklistTaskId) { this.checklistTaskId = checklistTaskId; }
    public Instant getOccurredAt() { return occurredAt; }
    public void setOccurredAt(Instant occurredAt) { this.occurredAt = occurredAt; }
    public String getSourceType() { return sourceType; }
    public void setSourceType(String sourceType) { this.sourceType = sourceType; }
    public Long getSourceId() { return sourceId; }
    public void setSourceId(Long sourceId) { this.sourceId = sourceId; }
    public String getEvidenceReference() { return evidenceReference; }
    public void setEvidenceReference(String evidenceReference) { this.evidenceReference = evidenceReference; }
    public String getDetails() { return details; }
    public void setDetails(String details) { this.details = details; }
    public String getRecordStatus() { return recordStatus; }
    public void setRecordStatus(String recordStatus) { this.recordStatus = recordStatus; }
    public Boolean getIsAutoGenerated() { return isAutoGenerated; }
    public void setIsAutoGenerated(Boolean isAutoGenerated) { this.isAutoGenerated = isAutoGenerated; }
    public Long getCreatedBy() { return createdBy; }
    public void setCreatedBy(Long createdBy) { this.createdBy = createdBy; }
    public Long getReviewedBy() { return reviewedBy; }
    public void setReviewedBy(Long reviewedBy) { this.reviewedBy = reviewedBy; }
    public Instant getReviewedAt() { return reviewedAt; }
    public void setReviewedAt(Instant reviewedAt) { this.reviewedAt = reviewedAt; }
    public String getReviewNote() { return reviewNote; }
    public void setReviewNote(String reviewNote) { this.reviewNote = reviewNote; }
}
