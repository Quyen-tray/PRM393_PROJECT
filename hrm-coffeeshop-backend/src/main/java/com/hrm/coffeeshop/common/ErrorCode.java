package com.hrm.coffeeshop.common;

import org.springframework.http.HttpStatus;

public enum ErrorCode {
    VALIDATION_ERROR(400), INVALID_CREDENTIALS(401), INVALID_TOKEN(401), UNAUTHENTICATED(401), PERMISSION_DENIED(403), METHOD_NOT_ALLOWED(405),
    ACCOUNT_NOT_ACTIVE(403), NOT_FOUND(404), CONFLICT(409), INVALID_STATE(409),
    BUSINESS_RULE_VIOLATION(422), TOO_MANY_REQUESTS(429), INTERNAL_ERROR(500),

    GPS_OUT_OF_RANGE(422), GPS_UNAVAILABLE(422), GPS_ACCURACY_INSUFFICIENT(422), GPS_STALE(422), GPS_MOCKED(422),
    DEVICE_NOT_ACTIVE(422), CAMERA_PERMISSION_DENIED(422), PHOTO_REQUIRED(422),
    PHOTO_ALREADY_USED(422), FACE_VERIFICATION_UNAVAILABLE(503),
    FACE_VERIFICATION_FAILED(422), SHIFT_NOT_FOUND(404), SHIFT_NOT_ELIGIBLE(422), EMPLOYEE_NOT_ELIGIBLE_FOR_SHIFT(422),
    CHECK_IN_TOO_EARLY(422), CHECK_IN_WINDOW_CLOSED(422),
    ATTENDANCE_ALREADY_CHECKED_IN(409), ATTENDANCE_ALREADY_CHECKED_OUT(409),
    ATTENDANCE_NOT_CHECKED_IN(409), ATTENDANCE_LOCKED(409), ATTENDANCE_ADJUSTMENT_PENDING(409),
    OVERTIME_NOT_APPROVED(422), CHECKLIST_REQUIRES_REVIEW(409), CHECKLIST_EVIDENCE_REQUIRED(422),
    DOCUMENT_REQUIREMENT_NOT_MET(422), TRAINING_REQUIREMENT_NOT_MET(422),
    PAYROLL_NOT_READY(422), PAYROLL_PERIOD_LOCKED(409);

    private final int status;
    ErrorCode(int status) { this.status = status; }
    public HttpStatus httpStatus() { return HttpStatus.valueOf(status); }
}
