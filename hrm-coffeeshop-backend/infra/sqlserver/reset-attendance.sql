-- Reset một bản chấm công dùng để test. Chạy thủ công trong SSMS, sau khi dừng backend.
-- Điền AttendanceId và EmployeeCode từ truy vấn trong docs/RESET_DATABASE.md.
-- CancelAssignment = 1: hủy phân ca tương ứng để quản lý có thể phân ca lại cùng giờ.
-- CancelAssignment = 0: giữ phân ca để check-in lại trên chính ca đó.
-- Không thay đổi tài khoản, thiết bị, cấu hình, đào tạo hoặc các ca khác.
USE HRM_CoffeeShop;
GO

DECLARE @AttendanceId BIGINT = NULL;
DECLARE @EmployeeCode VARCHAR(30) = NULL;
DECLARE @CancelAssignment BIT = 1;

SET NOCOUNT ON;
SET XACT_ABORT ON;

IF @AttendanceId IS NULL OR @AttendanceId <= 0 OR NULLIF(LTRIM(RTRIM(@EmployeeCode)), '') IS NULL
    THROW 51010, N'Điền AttendanceId và EmployeeCode của bản chấm công cần reset.', 1;

BEGIN TRY
    BEGIN TRANSACTION;
    DECLARE @ShiftAssignmentId BIGINT, @EmployeeId BIGINT, @WorkDate DATE, @PayrollStatus VARCHAR(20);
    SELECT @ShiftAssignmentId = a.ShiftAssignmentId, @EmployeeId = a.EmployeeId,
           @WorkDate = s.WorkDate, @PayrollStatus = a.PayrollStatus
    FROM dbo.Attendance a WITH (UPDLOCK, HOLDLOCK)
    JOIN dbo.ShiftAssignment s WITH (UPDLOCK, HOLDLOCK) ON s.ShiftAssignmentId = a.ShiftAssignmentId
    JOIN dbo.Employee e ON e.EmployeeId = a.EmployeeId
    WHERE a.AttendanceId = @AttendanceId AND e.EmployeeCode = @EmployeeCode;

    IF @ShiftAssignmentId IS NULL
        THROW 51011, N'Không tìm thấy bản chấm công thuộc đúng nhân viên đã chọn.', 1;

    IF @PayrollStatus <> 'OPEN' OR EXISTS (
        SELECT 1 FROM dbo.PayrollPeriod WHERE @WorkDate BETWEEN StartDate AND EndDate AND PeriodStatus <> 'OPEN'
    )
        THROW 51012, N'Công đã vào quy trình đối soát/chốt. Không reset bằng script test.', 1;

    IF EXISTS (SELECT 1 FROM dbo.AttendanceAdjustmentRequest WHERE AttendanceId = @AttendanceId)
       OR EXISTS (SELECT 1 FROM dbo.AttendanceAdjustmentHistory WHERE AttendanceId = @AttendanceId)
       OR EXISTS (SELECT 1 FROM dbo.AttendanceExceptionRequest WHERE AttendanceId = @AttendanceId OR ShiftAssignmentId = @ShiftAssignmentId)
       OR EXISTS (SELECT 1 FROM dbo.OvertimeRequest WHERE ShiftAssignmentId = @ShiftAssignmentId)
        THROW 51013, N'Ca đã có đơn giải trình, điều chỉnh hoặc OT. Script giữ nguyên các nghiệp vụ này.', 1;

    IF @CancelAssignment = 1 AND EXISTS (
        SELECT 1 FROM dbo.ChecklistTask WHERE ShiftAssignmentId = @ShiftAssignmentId
          AND RunStatus IN ('PENDING','IN_PROGRESS','SUBMITTED','OVERDUE','REJECTED')
    )
        THROW 51014, N'Ca còn checklist đang thực hiện hoặc chờ duyệt. Chọn CancelAssignment = 0 để giữ ca.', 1;

    DECLARE @Violations TABLE (Id BIGINT PRIMARY KEY);
    INSERT INTO @Violations SELECT ViolationEventId FROM dbo.ViolationEvent WHERE AttendanceId = @AttendanceId;
    IF EXISTS (SELECT 1 FROM dbo.ViolationEvent WHERE AttendanceId = @AttendanceId AND (IsAutoGenerated = 0 OR RecordStatus <> 'PENDING'))
       OR EXISTS (SELECT 1 FROM dbo.ViolationExplanation WHERE ViolationEventId IN (SELECT Id FROM @Violations))
       OR EXISTS (SELECT 1 FROM dbo.EmployeeRewardPenalty WHERE ViolationEventId IN (SELECT Id FROM @Violations))
        THROW 51015, N'Bản công liên quan vi phạm đã xử lý hoặc thưởng/phạt. Script giữ nguyên dữ liệu đó.', 1;

    DECLARE @BeforeJson NVARCHAR(MAX) = (
        SELECT AttendanceId, ShiftAssignmentId, EmployeeId, CheckInAt, CheckOutAt, PayrollStatus
        FROM dbo.Attendance WHERE AttendanceId = @AttendanceId FOR JSON PATH, WITHOUT_ARRAY_WRAPPER
    );
    DELETE FROM dbo.Notification
    WHERE (RelatedEntityType = 'Attendance' AND RelatedEntityId = @AttendanceId)
       OR (RelatedEntityType = 'ViolationEvent' AND RelatedEntityId IN (SELECT Id FROM @Violations));
    DELETE FROM dbo.ViolationEvent WHERE ViolationEventId IN (SELECT Id FROM @Violations);
    DELETE FROM dbo.AttendanceVerification WHERE AttendanceId = @AttendanceId;
    DELETE FROM dbo.Attendance WHERE AttendanceId = @AttendanceId;

    IF @CancelAssignment = 1
    BEGIN
        UPDATE dbo.ShiftAssignment SET ScheduleStatus = 'CANCELLED', UpdatedAt = SYSUTCDATETIME()
        WHERE ShiftAssignmentId = @ShiftAssignmentId;
        UPDATE dbo.Notification SET DeliveryStatus = 'CANCELLED'
        WHERE RelatedEntityType = 'ShiftAssignment' AND RelatedEntityId = @ShiftAssignmentId AND DeliveryStatus = 'PENDING';
    END;

    INSERT INTO dbo.AuditLog (ActorUserId, ActionCode, EntityType, EntityId, BeforeJson, AfterJson)
    VALUES (NULL, 'DEV_ATTENDANCE_RESET', 'Attendance', CONVERT(NVARCHAR(100), @AttendanceId), @BeforeJson,
            (SELECT @ShiftAssignmentId AS shiftAssignmentId, @CancelAssignment AS assignmentCancelled FOR JSON PATH, WITHOUT_ARRAY_WRAPPER));
    COMMIT TRANSACTION;

    SELECT @AttendanceId AS ResetAttendanceId, @EmployeeCode AS EmployeeCode,
           @ShiftAssignmentId AS ShiftAssignmentId, @CancelAssignment AS AssignmentCancelled;
END TRY
BEGIN CATCH
    IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
    THROW;
END CATCH;
